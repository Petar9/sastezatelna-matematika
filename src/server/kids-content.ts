import type { KidsProblem, KidsProfile } from "../core/kids.ts";

const competition = "Математика за всеки, 01.06.2024, 4. клас";
const authored = "Нова учебна задача по същата идея";
const money = (cents: number) => `${Math.floor(cents / 100)} лв.${cents % 100 ? ` и ${cents % 100} ст.` : ""}`;

function football(id: string, wins: number, matches: number, points: number, options: number[], original = false): KidsProblem {
	const draws = points - 3 * wins, losses = matches - wins - draws;
	return { id, topic: "Точки и брой мачове", source: original ? `${competition}, М1-03` : authored,
		text: original
			? "В едно първенство по футбол на всеки отбор при победа се дават 3 точки, при равенство - 1 точка, а при загуба - 0 точки. Отбор, участник в първенството, събрал 44 точки от 22 мача. Ако победите му са 13, колко са загубите му?"
			: `За победа се дават 3 точки, за равенство - 1, а за загуба - 0. Отбор има ${points} точки от ${matches} мача, от които ${wins} победи. Колко са загубите?`,
		options: options.map(String), correctIndex: options.indexOf(losses),
		hint: "Първо намери точките от победите. Останалите точки са от равенствата. Всеки равен мач носи точно 1 точка.",
		explanation: [
			`${wins} победи носят ${wins} · 3 = ${3 * wins} точки.`,
			`От равенствата остават ${points} - ${3 * wins} = ${draws} точки. Значи равните мачове са ${draws}.`,
			`От всички ${matches} мача изваждаме победите и равенствата: ${matches} - ${wins} - ${draws} = ${losses} загуби.`,
		],
		lesson: { title: "От точките към мачовете", steps: [
			"Разделяме мачовете на три групи: победи, равенства и загуби. Първо пресмятаме точките от победите.",
			"Изваждаме ги от всички точки. Остатъкът показва броя на равенствата, защото всяко носи 1 точка.",
			"Накрая от всички мачове изваждаме победите и равенствата. Остават загубите. Провери дали трите групи дават общия брой мачове.",
		] } };
}

function chocolates(id: string, cheap: number, dear: number, left: number, short: number, options: number[], original = false): KidsProblem {
	const difference = dear - cheap, count = (left + short) / difference, total = count * cheap + left;
	return { id, topic: "Остават и не достигат", source: original ? `${competition}, М1-04` : authored,
		text: original
			? "Шоколад „Милка“ струва 3 лв. и 50 ст., а шоколад „Линд“ 4 лв. и 50 ст. Ако си купя няколко шоколада „Милка“, ще ми останат 3 лева. За да си купя същия брой шоколади „Линд“, не ми достигат 4 лева. Парите, които имам у себе си, са:"
			: `Един тефтер струва ${money(cheap)}, а друг вид - ${money(dear)} Ако купя няколко от по-евтините, остават ${money(left)} За същия брой от по-скъпите не достигат ${money(short)} Колко пари имам?`,
		options: options.map(money), correctIndex: options.indexOf(total),
		hint: "При по-евтината покупка има останали пари, а при по-скъпата има недостиг. Събери тези две суми. После сравни цената на по един предмет.",
		explanation: [
			`По-скъпият предмет струва с ${money(difference)} повече. Двете покупки се различават с ${money(left)} + ${money(short)} = ${money(left + short)}`,
			`В стотинки: ${left + short} : ${difference} = ${count}. Това е броят на предметите.`,
			`Имам стойността на по-евтината покупка и останалите пари: ${count} · ${cheap} + ${left} = ${total} ст., тоест ${money(total)}`,
		],
		lesson: { title: "Защо събираме остатъка и недостига?", steps: [
			"Представи си трите суми подред: по-евтината покупка → моите пари → по-скъпата покупка.",
			"От първата до моите пари има остатък. От моите пари до втората има недостиг. Целият път е остатък + недостиг.",
			"Разделяме тази разлика на оскъпяването на един предмет. Получаваме броя. После намираме парите: евтината покупка + остатъка.",
		] } };
}

function years(id: string, start: number, options: number[], original = false): KidsProblem {
	const answer = 2103 - start;
	return { id, topic: "Цифри и векове", source: original ? `${competition}, М1-01` : authored,
		text: original
			? "2024-та година може да се нарече „интересна“, защото сумата на първите три цифри е равна на четвъртата (2 + 0 + 2 = 4). След колко години ще е първата „интересна“ година от следващия век?"
			: `Наричаме година „интересна“, ако сборът на първите три цифри е равен на четвъртата. Сега е ${start} година. След колко години ще настъпи първата „интересна“ година от следващия век?`,
		options: options.map(String), correctIndex: options.indexOf(answer),
		hint: "Следващият век започва с 2101 година. Провери годините оттам нататък. Търсим колко години ще минат, а не само коя ще е годината.",
		explanation: [
			"Следващият век започва през 2101 г. За 2101 и 2102 сборът 2 + 1 + 0 = 3 не съвпада с последната цифра.",
			"За 2103 г. имаме 2 + 1 + 0 = 3. Тя е първата подходяща година.",
			`Намираме колко време ще мине: 2103 - ${start} = ${answer} години.`,
		],
		lesson: { title: "Годината и времето до нея са различни отговори", steps: [
			"Първо определяме от коя година започва търсеният век. XXII век започва през 2101 г.",
			"Проверяваме годините подред по правилото за цифрите. Така сме сигурни, че не пропускаме по-ранна подходяща година.",
			"Накрая прочитаме въпроса отново. Ако пита „след колко години“, изваждаме сегашната година от намерената.",
		] } };
}

function inverse(id: string, total: number, factor: number, add: number, options: string[], answer: number, original = false): KidsProblem {
	return { id, topic: "Обратни действия", source: original ? `${competition}, М1-02` : authored,
		text: original
			? "Неизвестното число x в равенството 2024 : ((2024 - x) · 20 + 24) = 1 е:"
			: `Кое е неизвестното число x в равенството ${total} : ((${total} - x) · ${factor} + ${add}) = 1?`,
		options, correctIndex: options.indexOf(String(answer)),
		hint: "За да получим 1 при деление, делителят трябва да е равен на делимото. После връщай действията в скобите от последното към първото.",
		explanation: [
			`Делимото е ${total}, а частното е 1. Значи целият делител в скобите е ${total}.`,
			`Преди прибавянето на ${add} стойността е ${total} - ${add} = ${total - add}. Преди умножението по ${factor} е ${(total - add)} : ${factor} = ${(total - add) / factor}.`,
			`Следователно ${total} - x = ${(total - add) / factor}. Търсеното число е ${total} - ${(total - add) / factor} = ${answer}.`,
		],
		lesson: { title: "Връщаме действията назад", steps: [
			"Когато число, разделено на скобата, дава 1, стойността на скобата е същото число.",
			"Връщаме последното действие: прибавянето отменяме с изваждане, а умножението - с деление.",
			"Когато стигнем до разликата, намираме неизвестното умалително. После заместваме отговора в първоначалния израз за проверка.",
		] } };
}

function clock(id: string, start: number, hours: number, options: number[], original = false): KidsProblem {
	const days = Math.floor(hours / 24), remainder = hours % 24, answer = (start + remainder) % 24;
	return { id, topic: "Часове и денонощия", source: original ? `${competition}, М1-12` : authored,
		text: original ? "Сега е 10 часът. След изтичане на 2024 часа ще бъде:"
			: `Сега е ${start} часът. Колко ще е часът след ${hours} часа?`,
		options: options.map(n => `${n} часът`), correctIndex: options.indexOf(answer),
		hint: "След всяко цяло денонощие часът е същият. Колко часа остават, ако отделиш групите по 24?",
		explanation: [
			`${hours} = ${days} · 24 + ${remainder}. Това са ${days} цели денонощия и още ${remainder} часа.`,
			`Целите денонощия не променят часа. Прибавяме само остатъка: ${start} + ${remainder} = ${start + remainder}.`,
			start + remainder >= 24 ? `Минаваме през полунощ: ${start + remainder} - 24 = ${answer}. Ще бъде ${answer} часът.` : `Ще бъде ${answer} часът.`,
		],
		lesson: { title: "Прескачаме целите денонощия", steps: [
			"Едно денонощие има 24 часа. След 24, 48 или 72 часа часовникът показва същия час.",
			"Отделяме целите групи по 24. За показанието на часовника ни интересува само остатъкът.",
			"Прибавяме остатъка към началния час. Ако сборът е 24 или повече, изваждаме 24, защото сме минали през полунощ.",
		] } };
}

function ages(id: string, before: number, after: number, past: number, future: number, options: number[], original = false): KidsProblem {
	const interval = past + future, answer = (after - before) / interval;
	return { id, topic: "Обща възраст", source: original ? `${competition}, М1-13` : authored,
		text: original
			? "Сумата от годините на учениците от нашия клас преди 2 години беше 200 години, а след две години сумата от годините ни ще е 280. Колко сме?"
			: `Преди ${past} години сборът от възрастите на децата в една група беше ${before}. След ${future} години сборът ще е ${after}. Броят на децата не се променя. Колко са те?`,
		options: options.map(String), correctIndex: options.indexOf(answer),
		hint: "Колко години минават от „преди“ до „след“? С толкова пораства всяко дете. Сравни това с увеличението на общия сбор.",
		explanation: [
			`От преди ${past} години до след ${future} години минават ${past} + ${future} = ${interval} години.`,
			`Общият сбор се увеличава с ${after} - ${before} = ${after - before} години. Всяко дете добавя по ${interval} години.`,
			`Броят на децата е ${after - before} : ${interval} = ${answer}. Проверка: ${answer} · ${interval} = ${after - before}.`,
		],
		lesson: { title: "Пораства всяко дете", steps: [
			"Нареди времето: преди → сега → след. Събери двата периода, за да намериш целия изминал срок.",
			"Всяко дете пораства с един и същ брой години. Затова разликата в общия сбор се състои от еднакви части.",
			"Раздели увеличението на общата възраст на годините за едно дете. Не е нужно да знаем отделните възрасти.",
		] } };
}

