// Run explicitly only when establishing an initial scope for a new competition.
// Keep existing entries fixed; catalogue additions must not rebase legacy profiles.
import fs from "node:fs";
import { availableCompetitions, competitionContent } from "../src/server/competitions.ts";
import { currentPreparationScope } from "../src/core/preparation.ts";
const target = new URL("../src/core/preparation-baselines.ts", import.meta.url);
const existing = fs.existsSync(target) ? (await import(target.href)).preparationBaselines : {};
const baselines = { ...existing };
for (const competition of availableCompetitions()) baselines[competition.id] ??= currentPreparationScope(competitionContent(competition.id));
fs.writeFileSync(target, '// Generated by scripts/generate-preparation-baseline.ts. Existing entries are immutable.\nimport type { PreparationScope } from "./preparation.ts";\nexport const preparationBaselines: Record<string, PreparationScope> = ' + JSON.stringify(baselines, null, 1) + ';\n');
