import assert from "node:assert/strict";
import { after, test } from "node:test";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { competitionCookie, competitionCookieName, resumedCompetition } from "../src/server/competition-resume.ts";
import { DEFAULT_COMPETITION_ID } from "../src/core/competitions.ts";
import { kidsCourseResponse } from "../src/server/kids-course.ts";
import { createKidsCourseStore } from "../src/store/kids-course.ts";
import { kidsCourseContent as content } from "../src/server/kids-course-content.ts";
import type { CourseAction, KidsCourseView } from "../src/core/kids-course.ts";
const directory=fs.mkdtempSync(path.join(os.tmpdir(),"maths-resume-"));
after(()=>fs.rmSync(directory,{recursive:true,force:true}));
test("resume respects explicit URLs, available competitions and separate child cookies",()=>{
 const available=[DEFAULT_COMPETITION_ID,"nvo","olimpiada"];
 assert.equal(resumedCompetition("olimpiada","nvo",available),"olimpiada");
 assert.equal(resumedCompetition(undefined,"nvo",available),"nvo");
 assert.equal(resumedCompetition(undefined,"retired",available),DEFAULT_COMPETITION_ID);
 assert.equal(resumedCompetition(undefined,undefined,available),DEFAULT_COMPETITION_ID);
 assert.notEqual(competitionCookieName("child-a"),competitionCookieName("child-b"));
 assert.equal(competitionCookie(undefined,"nvo",false),"maths_competition_local=nvo; Path=/; Max-Age=31536000; HttpOnly; SameSite=Lax");
 assert.ok(competitionCookie("child-a","nvo",true).endsWith("; Secure"));
});
test("only saved graded work and completed reveal update resume, never reads, navigation, hints or failed saves",async()=>{
 const store=createKidsCourseStore(path.join(directory,"course"));
 const cookie=competitionCookie("child-a","matematika-za-vseki",true);
 const send=(revision:number,action:CourseAction)=>kidsCourseResponse(new Request("https://example.test/api/kids/course",{method:"POST",body:JSON.stringify({revision,action})}),store,content,cookie);
 const view=async(response:Response)=>(await response.json() as {course:KidsCourseView}).course;
 const get=await kidsCourseResponse(new Request("https://example.test/api/kids/course"),store,content,cookie);
 assert.equal(get.headers.get("Set-Cookie"),null);assert.deepEqual(fs.readdirSync(directory),[]);
 const select=await send(0,{type:"selectTopic",topicId:"matches"});
 assert.equal(select.headers.get("Set-Cookie"),null);let c=await view(select);
 const key=c.task!.key;
 const draft=await send(c.revision,{type:"saveDraft",taskKey:key,partIndex:0,answers:["1"]});
 assert.equal(draft.headers.get("Set-Cookie"),null);c=await view(draft);
 const hint=await send(c.revision,{type:"hint",taskKey:key});
 assert.equal(hint.headers.get("Set-Cookie"),null);c=await view(hint);
 const invalid=await send(c.revision,{type:"answer",taskKey:"stale",answers:["0"]});
 assert.notEqual(invalid.status,200);assert.equal(invalid.headers.get("Set-Cookie"),null);
 const wrong=await send(c.revision,{type:"answer",taskKey:key,answers:["1"]});
 assert.equal(wrong.status,200);assert.equal(wrong.headers.get("Set-Cookie"),cookie);c=await view(wrong);
 const stale=await send(c.revision-1,{type:"answer",taskKey:key,answers:["0"]});
 assert.equal(stale.status,409);assert.equal(stale.headers.get("Set-Cookie"),null);
 const selected=await send(c.revision,{type:"selectTopic",topicId:"clocks"});c=await view(selected);
 const firstHelp=await send(c.revision,{type:"dontKnow",taskKey:c.task!.key});
 assert.equal(firstHelp.headers.get("Set-Cookie"),null);c=await view(firstHelp);
 const reveal=await send(c.revision,{type:"dontKnow",taskKey:c.task!.key});
 assert.equal(reveal.headers.get("Set-Cookie"),cookie);assert.equal((await view(reveal)).task!.outcome,"revealed");
 const failure=await kidsCourseResponse(new Request("https://example.test/api/kids/course",{method:"POST",body:JSON.stringify({revision:0,action:{type:"dashboard"}})}),{read:()=>{throw new Error("Unavailable");},update:()=>{throw new Error("Unavailable");}},content,cookie);
 assert.equal(failure.status,500);assert.equal(failure.headers.get("Set-Cookie"),null);
});
